namespace Passenger.Debugger.Decompilation;

// ILSpy's PortablePdbWriter (ICSharpCode.Decompiler/DebugInfo/PortablePdbWriter.cs), Copyright (c) 2018 Siegfried
// Pammer, under the MIT licence THIRD_PARTY_NOTICES.md gives in full; changed to decompile its files in parallel and
// return their text. A change that moves what it maps raises SymbolCache.Format, so no cached PDB of the old one is read.
public class PortablePdbWriter2
{
    private const string decompilerVersion = DecompilerVersionInfo.Version;

    /// <summary>Suppresses the "generated by ICSharpCode.Decompiler" header comment in each source file.</summary>
    public bool NoLogo { get; set; }

    /// <summary>
    /// The PDB id (GUID + stamp) to stamp into the generated PDB. When <c>null</c> (the default) the
    /// id is taken from the assembly's CodeView debug-directory entry so the PDB matches the PE.
    /// </summary>
    public BlobContentId? PdbId { get; set; }

    /// <summary>Optional per-file progress reporter.</summary>
    public IProgress<DecompilationProgress>? Progress { get; set; }

    /// <summary>The title surfaced through <see cref="Progress"/>.</summary>
    public string CurrentProgressTitle { get; set; } = "Generating portable PDB...";

    /// <summary>When true (the default) each decompiled source file is embedded into the PDB; false when the source is
    /// already on disk, so the PDB stays small and references the files there. The per-document checksum is written
    /// either way.</summary>
    public bool EmbedSourceFiles { get; set; } = true;

    public static bool HasCodeViewDebugDirectoryEntry(PEFile file)
    {
        return file != null && file.Reader.ReadDebugDirectory().Any(entry => entry.Type == DebugDirectoryEntryType.CodeView);
    }

    private static bool IncludeTypeWhenGeneratingPdb(PEFile module, TypeDefinitionHandle type, DecompilerSettings settings)
    {
        MetadataReader metadata = module.Metadata;
        TypeDefinition typeDef = metadata.GetTypeDefinition(type);
        string name = metadata.GetString(typeDef.Name);
        string ns = metadata.GetString(typeDef.Namespace);
        if (name == "<Module>" || CSharpDecompiler.MemberIsHidden(module, type, settings))
        {
            return false;
        }

        if (ns == "XamlGeneratedNamespace" && name == "GeneratedInternalTypeHelper")
        {
            return false;
        }

        if (!typeDef.IsNested && RemoveEmbeddedAttributes.attributeNames.Contains(ns + "." + name))
        {
            return false;
        }

        return true;
    }

    private static CSharpDecompiler NewDecompiler(DecompilerTypeSystem decompilerTypeSystem, DecompilerSettings decompilerSettings)
    {
        CSharpDecompiler decompiler = new CSharpDecompiler(decompilerTypeSystem, decompilerSettings)
        {
            AstTransforms = {
                new EscapeInvalidIdentifiers(),
                new RemoveCLSCompliantAttribute()
				// most other transforms are already present by default
			}
        };
        return decompiler;
    }

    public Dictionary<string, string> WritePdb(
        PEFile file,
        DecompilerTypeSystem decompilerTypeSystem,
        DecompilerSettings settings,
        Stream targetStream,
        int maxDegreeOfParallelism = -1,
        CancellationToken cancellationToken = default)
    {
        BlobContentId? pdbId = PdbId;
        MetadataBuilder metadata = new MetadataBuilder();
        MetadataReader reader = file.Metadata;
        MethodDefinitionHandle entrypointHandle = MetadataTokens.MethodDefinitionHandle((file.Reader.PEHeaders.CorHeader ?? throw new BadImageFormatException("Not a .NET assembly")).EntryPointTokenOrRelativeVirtualAddress);

        Dictionary<MethodDefinitionHandle, (DocumentHandle Document, BlobHandle SequencePoints)> sequencePointBlobs = new Dictionary<MethodDefinitionHandle, (DocumentHandle Document, BlobHandle SequencePoints)>();
        List<(MethodDefinitionHandle Method, ImportScopeInfo Import, int Offset, int Length, HashSet<ILVariable> Locals)> localScopes = new List<(MethodDefinitionHandle Method, ImportScopeInfo Import, int Offset, int Length, HashSet<ILVariable> Locals)>();
        List<(MethodDefinitionHandle MoveNextMethod, MethodDefinitionHandle KickoffMethod)> stateMachineMethods = new List<(MethodDefinitionHandle MoveNextMethod, MethodDefinitionHandle KickoffMethod)>();
        List<(EntityHandle Parent, GuidHandle Guid, BlobHandle Blob)> customDebugInfo = new List<(EntityHandle Parent, GuidHandle Guid, BlobHandle Blob)>();
        List<(MethodDefinitionHandle Parent, GuidHandle Guid, BlobHandle Blob)> customMethodDebugInfo = new List<(MethodDefinitionHandle Parent, GuidHandle Guid, BlobHandle Blob)>();
        ImportScopeHandle globalImportScope = metadata.AddImportScope(default, default);
        Dictionary<string, string> collectedSourceFiles = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

        string assemblyName = reader.GetString(reader.GetAssemblyDefinition().Name);
        Guid mvid = reader.GetGuid(reader.GetModuleDefinition().Mvid);
        string sourceFilePrefix = Path.Combine("decompiled", assemblyName, mvid.ToString());

        string BuildFileNameFromTypeName(TypeDefinitionHandle handle)
        {
            TopLevelTypeName typeName = handle.GetFullTypeName(reader).TopLevelTypeName;
            string ns = settings.UseNestedDirectoriesForNamespaces
                ? WholeProjectDecompiler.CleanUpPath(typeName.Namespace)
                : WholeProjectDecompiler.CleanUpDirectoryName(typeName.Namespace);
            return Path.Combine(sourceFilePrefix, ns, WholeProjectDecompiler.CleanUpFileName(typeName.Name, ".cs"));
        }

        List<IGrouping<string, TypeDefinitionHandle>> sourceFiles = reader.GetTopLevelTypeDefinitions().Where(t => IncludeTypeWhenGeneratingPdb(file, t, settings)).GroupBy(BuildFileNameFromTypeName).ToList();
        DecompilationProgress currentProgress = new()
        {
            TotalUnits = sourceFiles.Count,
            UnitsCompleted = 0,
            Title = CurrentProgressTitle
        };

        ConcurrentBag<PerFileResult> perFileResults = new ConcurrentBag<PerFileResult>();

        Parallel.ForEach(
            Partitioner.Create(sourceFiles, loadBalance: true),
            new ParallelOptions
            {
                MaxDegreeOfParallelism = maxDegreeOfParallelism <= 0 ? Environment.ProcessorCount : maxDegreeOfParallelism,
                CancellationToken = cancellationToken
            },
            sourceFile =>
            {
                // Create a per-task decompiler that shares the same type system but is otherwise independent.
                CSharpDecompiler taskDecompiler = NewDecompiler(decompilerTypeSystem, settings);
                taskDecompiler.CancellationToken = cancellationToken;

                SyntaxTree syntaxTree = taskDecompiler.DecompileTypes(sourceFile);

                if (Progress != null)
                {
                    Interlocked.Increment(ref currentProgress.UnitsCompleted);
                    Progress.Report(currentProgress);
                }

                if (!syntaxTree.HasChildren)
                {
                    return;
                }

                if (!NoLogo)
                {
                    syntaxTree.PrependLeadingTrivia(new Comment(" PDB and source generated by ICSharpCode.Decompiler " + decompilerVersion));
                }

                string sourceText = SyntaxTreeToString(syntaxTree, settings);

                Dictionary<ILFunction, List<SequencePoint>> sequencePoints = taskDecompiler.CreateSequencePoints(syntaxTree);

                // Per task, sharing no state with another.
                DebugInfoGenerator debugInfoGen = new DebugInfoGenerator(taskDecompiler.TypeSystem);
                syntaxTree.AcceptVisitor(debugInfoGen);

                perFileResults.Add(new PerFileResult(sourceFile.Key, sourceText, syntaxTree, sequencePoints, debugInfoGen));
            });

        foreach (PerFileResult result in perFileResults)
        {
            // The document hash is always required; the source blob is only embedded when asked.
            byte[] sourceCheckSum = ComputeSourceChecksum(result.SourceText);
            BlobHandle name = metadata.GetOrAddDocumentName(result.Key);

            DocumentHandle document = metadata.AddDocument(name,
                hashAlgorithm: metadata.GetOrAddGuid(KnownGuids.HashAlgorithmSHA256),
                hash: metadata.GetOrAddBlob(sourceCheckSum),
                language: metadata.GetOrAddGuid(KnownGuids.CSharpLanguageGuid));

            if (EmbedSourceFiles)
            {
                customDebugInfo.Add((document,
                    metadata.GetOrAddGuid(KnownGuids.EmbeddedSource),
                    WriteSourceToBlob(metadata, result.SourceText)));
            }

            result.DebugInfoGen.GenerateImportScopes(metadata, globalImportScope);

            localScopes.AddRange(result.DebugInfoGen.LocalScopes);

            collectedSourceFiles[result.Key] = result.SourceText;

            foreach (ILFunction? function in result.DebugInfoGen.Functions)
            {
                IMethod method = function.MoveNextMethod ?? function.Method ?? throw new InvalidOperationException("Function does not have a method associated with it");
                MethodDefinitionHandle methodHandle = (MethodDefinitionHandle)method.MetadataToken;
                result.SequencePoints.TryGetValue(function, out List<SequencePoint>? points);
                ProcessMethod(methodHandle, document, points, result.SyntaxTree);
                if (function is { MoveNextMethod: { } moveNext, Method: { } kickoff })
                {
                    stateMachineMethods.Add((
                        (MethodDefinitionHandle)moveNext.MetadataToken,
                        (MethodDefinitionHandle)kickoff.MetadataToken
                    ));
                    customDebugInfo.Add((
                        moveNext.MetadataToken,
                        metadata.GetOrAddGuid(KnownGuids.StateMachineHoistedLocalScopes),
                        metadata.GetOrAddBlob(BuildStateMachineHoistedLocalScopes(function))
                    ));
                }
                // A runtime-async method (.NET 11) has no state machine, so no awaits and no stepping information.
                if (function.IsAsync && !function.AsyncDebugInfo.Awaits.IsDefault)
                {
                    customMethodDebugInfo.Add((methodHandle,
                        metadata.GetOrAddGuid(KnownGuids.MethodSteppingInformation),
                        metadata.GetOrAddBlob(function.AsyncDebugInfo.BuildBlob(methodHandle))));
                }
            }

            // Constructors the output omits (implicit or primary) keep their lifted initializers' sequence points here.
            HashSet<ILFunction> emittedFunctions = new HashSet<ILFunction>(result.DebugInfoGen.Functions);
            foreach ((ILFunction? function, List<SequencePoint>? points) in result.SequencePoints)
            {
                if (!emittedFunctions.Add(function))
                {
                    continue;
                }

                IMethod? method = function.MoveNextMethod ?? function.Method;
                if (method == null || method.MetadataToken.IsNil)
                {
                    continue;
                }

                ProcessMethod((MethodDefinitionHandle)method.MetadataToken, document, points, result.SyntaxTree);
            }
        }

        foreach (MethodDefinitionHandle method in reader.MethodDefinitions)
        {
            MethodDefinition md = reader.GetMethodDefinition(method);

            if (sequencePointBlobs.TryGetValue(method, out (DocumentHandle Document, BlobHandle SequencePoints) info))
            {
                metadata.AddMethodDebugInformation(info.Document, info.SequencePoints);
            }
            else
            {
                metadata.AddMethodDebugInformation(default, default);
            }
        }

        localScopes.Sort((x, y) =>
        {
            if (x.Method != y.Method)
            {
                return MetadataTokens.GetRowNumber(x.Method) - MetadataTokens.GetRowNumber(y.Method);
            }
            if (x.Offset != y.Offset)
            {
                return x.Offset - y.Offset;
            }
            return y.Length - x.Length;
        });
        foreach ((MethodDefinitionHandle Method, ImportScopeInfo Import, int Offset, int Length, HashSet<ILVariable> Locals) localScope in localScopes)
        {
            int nextRow = metadata.GetRowCount(TableIndex.LocalVariable) + 1;
            LocalVariableHandle firstLocalVariable = MetadataTokens.LocalVariableHandle(nextRow);

            foreach (ILVariable? local in localScope.Locals.OrderBy(l => l.Index))
            {
                StringHandle localVarName = local.Name != null ? metadata.GetOrAddString(local.Name) : default;
                metadata.AddLocalVariable(LocalVariableAttributes.None, local.Index ?? throw new InvalidOperationException($"Local '{local.Name}' has no slot"), localVarName);
            }

            metadata.AddLocalScope(localScope.Method, localScope.Import.Handle, firstLocalVariable,
                default, localScope.Offset, localScope.Length);
        }

        stateMachineMethods.SortBy(row => MetadataTokens.GetRowNumber(row.MoveNextMethod));
        foreach ((MethodDefinitionHandle MoveNextMethod, MethodDefinitionHandle KickoffMethod) row in stateMachineMethods)
        {
            metadata.AddStateMachineMethod(row.MoveNextMethod, row.KickoffMethod);
        }
        customMethodDebugInfo.SortBy(row => MetadataTokens.GetRowNumber(row.Parent));
        foreach ((MethodDefinitionHandle Parent, GuidHandle Guid, BlobHandle Blob) row in customMethodDebugInfo)
        {
            metadata.AddCustomDebugInformation(row.Parent, row.Guid, row.Blob);
        }
        customDebugInfo.SortBy(row => MetadataTokens.GetRowNumber(row.Parent));
        foreach ((EntityHandle Parent, GuidHandle Guid, BlobHandle Blob) row in customDebugInfo)
        {
            metadata.AddCustomDebugInformation(row.Parent, row.Guid, row.Blob);
        }

        if (pdbId == null)
        {
            DebugDirectoryEntry? debugDir = file.Reader.ReadDebugDirectory().Cast<DebugDirectoryEntry?>().LastOrDefault(dir => dir!.Value.Type == DebugDirectoryEntryType.CodeView);
            if (debugDir is not null)
            {
                CodeViewDebugDirectoryData portable = file.Reader.ReadCodeViewDebugDirectoryData(debugDir.Value);
                Debug.Assert(!portable.Path.EndsWith(".ni.pdb"));
                pdbId = new BlobContentId(portable.Guid, debugDir.Value.Stamp);
            }
            else
            {
                throw new InvalidOperationException("Dll did not contain a CodeView entry, unable to determine PdbId. Are you trying to decompile a Publicized assembly?");
            }
        }

        PortablePdbBuilder serializer = new PortablePdbBuilder(metadata, GetRowCounts(reader), entrypointHandle, blobs => pdbId.Value);
        BlobBuilder blobBuilder = new BlobBuilder();
        serializer.Serialize(blobBuilder);
        blobBuilder.WriteContentTo(targetStream);

        return collectedSourceFiles;

        void ProcessMethod(MethodDefinitionHandle method, DocumentHandle document,
            List<SequencePoint>? sequencePoints, SyntaxTree syntaxTree)
        {
            MethodDefinition methodDef = reader.GetMethodDefinition(method);
            int localSignatureRowId;
            MethodBodyBlock? methodBody;
            if (methodDef.RelativeVirtualAddress != 0)
            {
                methodBody = file.Reader.GetMethodBody(methodDef.RelativeVirtualAddress);
                localSignatureRowId = methodBody.LocalSignature.IsNil ? 0 : MetadataTokens.GetRowNumber(methodBody.LocalSignature);
            }
            else
            {
                methodBody = null;
                localSignatureRowId = 0;
            }

            // An ILFunction can be defined in C# twice: a generated function made a lambda but left in the tree.
            if (!sequencePointBlobs.ContainsKey(method))
            {
                if (sequencePoints?.Count > 0)
                {
                    sequencePointBlobs.Add(method, (document, EncodeSequencePoints(metadata, localSignatureRowId, sequencePoints)));
                }
                else
                {
                    sequencePointBlobs.Add(method, (default, default));
                }
            }
            else
            {
                Debug.Assert(false, "Duplicate sequence point definition detected: " + MetadataTokens.GetToken(method).ToString("X8"));
            }
        }
    }

    private static BlobBuilder BuildStateMachineHoistedLocalScopes(ILFunction function)
    {
        BlobBuilder builder = new BlobBuilder();
        foreach (IField field in function.Variables.Select(v => v.StateMachineField).OfType<IField>().OrderBy(f => MetadataTokens.GetRowNumber(f.MetadataToken)))
        {
            builder.WriteUInt32(0);
            builder.WriteUInt32((uint)function.CodeSize);
        }
        return builder;
    }

    private static byte[] ComputeSourceChecksum(string sourceText)
    {
        byte[] bytes = Encoding.UTF8.GetBytes(sourceText);
        using SHA256 hasher = SHA256.Create();
        return hasher.ComputeHash(bytes);
    }

    private static BlobHandle WriteSourceToBlob(MetadataBuilder metadata, string sourceText)
    {
        BlobBuilder builder = new BlobBuilder();
        using (MemoryStream memory = new MemoryStream())
        {
            DeflateStream deflate = new DeflateStream(memory, CompressionLevel.Optimal, leaveOpen: true);
            byte[] bytes = Encoding.UTF8.GetBytes(sourceText);
            deflate.Write(bytes, 0, bytes.Length);
            deflate.Close();
            byte[] buffer = memory.ToArray();
            builder.WriteInt32(bytes.Length); // compressed
            builder.WriteBytes(buffer);
        }

        return metadata.GetOrAddBlob(builder);
    }

    private static BlobHandle EncodeSequencePoints(MetadataBuilder metadata, int localSignatureRowId, List<SequencePoint> sequencePoints)
    {
        if (sequencePoints.Count == 0)
        {
            return default;
        }

        BlobBuilder writer = new BlobBuilder();
        // header:
        writer.WriteCompressedInteger(localSignatureRowId);

        int previousOffset = -1;
        int previousStartLine = -1;
        int previousStartColumn = -1;

        for (int i = 0; i < sequencePoints.Count; i++)
        {
            SequencePoint sequencePoint = sequencePoints[i];
            // delta IL offset:
            if (i > 0)
            {
                writer.WriteCompressedInteger(sequencePoint.Offset - previousOffset);
            }
            else
            {
                writer.WriteCompressedInteger(sequencePoint.Offset);
            }

            previousOffset = sequencePoint.Offset;

            if (sequencePoint.IsHidden)
            {
                writer.WriteInt16(0);
                continue;
            }

            int lineDelta = sequencePoint.EndLine - sequencePoint.StartLine;
            int columnDelta = sequencePoint.EndColumn - sequencePoint.StartColumn;

            writer.WriteCompressedInteger(lineDelta);

            if (lineDelta == 0)
            {
                writer.WriteCompressedInteger(columnDelta);
            }
            else
            {
                writer.WriteCompressedSignedInteger(columnDelta);
            }

            if (previousStartLine < 0)
            {
                writer.WriteCompressedInteger(sequencePoint.StartLine);
                writer.WriteCompressedInteger(sequencePoint.StartColumn);
            }
            else
            {
                writer.WriteCompressedSignedInteger(sequencePoint.StartLine - previousStartLine);
                writer.WriteCompressedSignedInteger(sequencePoint.StartColumn - previousStartColumn);
            }

            previousStartLine = sequencePoint.StartLine;
            previousStartColumn = sequencePoint.StartColumn;
        }

        return metadata.GetOrAddBlob(writer);
    }

    private static ImmutableArray<int> GetRowCounts(MetadataReader reader)
    {
        ImmutableArray<int>.Builder builder = ImmutableArray.CreateBuilder<int>(MetadataTokens.TableCount);
        for (int i = 0; i < MetadataTokens.TableCount; i++)
        {
            builder.Add(reader.GetTableRowCount((TableIndex)i));
        }

        return builder.MoveToImmutable();
    }

    private static string SyntaxTreeToString(SyntaxTree syntaxTree, DecompilerSettings settings)
    {
        StringWriter w = new StringWriter();
        TokenWriter tokenWriter = new TextWriterTokenWriter(w);
        tokenWriter = TokenWriter.WrapInWriterThatSetsLocationsInAST(tokenWriter);
        syntaxTree.AcceptVisitor(new CSharpOutputVisitor(tokenWriter, settings.CSharpFormattingOptions));
        return w.ToString();
    }

    private sealed record PerFileResult(
        string Key,
        string SourceText,
        SyntaxTree SyntaxTree,
        Dictionary<ILFunction, List<SequencePoint>> SequencePoints,
        DebugInfoGenerator DebugInfoGen);
}
