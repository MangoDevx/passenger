#!/usr/bin/env python3
"""Every comment in the repository held to the house limits: a file's or type's at most 10 lines, a member's (a method,
property, field, function, recipe or style) at most 5, and one inside a body at most 1. Prints each comment over its
limit as path:line, what it sits on, its limit and its length, and fails when any is. What a comment says (only of what
it sits on, never how something else works) is the reader's to hold; this holds its length.

python3 -I tools/check-comments.py [PATH...]    (just comments)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILE_LIMIT, TYPE_LIMIT, MEMBER_LIMIT, BODY_LIMIT = 10, 10, 5, 1

# Recovered or generated, whose comments are their sources': the debugger's COM declarations (ICorDebugSharp's) and
# protoc's output of Aspire's protocol; a file a tool writes is held through that tool, and the debuggees' lines are
# what their tests stop at.
SKIPPED = ("src/Passenger.Debugger.Interop/", "src/Passenger.App/Aspire/Protocol/", "tests/Debuggees/", "artifacts/",
           "node_modules/", "/obj/", "/bin/", ".git/")
WRITTEN_BY = re.compile(r"Written by tools/|<auto-generated|tools/themes\.py from its palette")

TYPE = re.compile(r"^\s*(?:\[.*\]\s*)*(?:(?:public|internal|private|protected|file|static|sealed|abstract|partial|readonly|"
                  r"unsafe|ref|new)\s+)*(?:class|struct|interface|enum|record|delegate)\b")
MEMBER = re.compile(r"^\s*(?:public|internal|private|protected|override|static|async|const|readonly|event|abstract|virtual|"
                    r"unsafe|extern|new|partial|required|implicit|explicit|file|sealed|volatile)\b")


def held(path):
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    return not any(part in "/" + relative for part in ("/" + s if not s.startswith("/") else s for s in SKIPPED))


def written_by_tool(lines):
    return any(WRITTEN_BY.search(line) for line in lines[:8])


def runs(lines, starts, ends=None):
    """Consecutive comment lines: (first index, count). `starts` matches a comment line; a block comment from a line
    matching `starts` that `ends` closes counts each of its lines."""
    found, at = [], 0
    while at < len(lines):
        if starts(lines[at]):
            first = at
            if ends is not None and not ends(lines[at]):
                while at + 1 < len(lines) and not ends(lines[at]):
                    at += 1
            at += 1
            while at < len(lines) and starts(lines[at]):
                if ends is not None and not ends(lines[at]):
                    while at + 1 < len(lines) and not ends(lines[at]):
                        at += 1
                at += 1
            found.append((first, at - first))
        else:
            at += 1
    return found


def subject(lines, after, skip=r"^\s*(\[.*\]\s*)?$"):
    for line in lines[after:]:
        if not re.match(skip, line):
            return line
    return ""


def code_before(lines, index, comment):
    return any(line.strip() and not comment(line) for line in lines[:index])


def code_only(lines):
    """The lines with those inside a raw or verbatim string blanked: a test's C# source held as text is its input, not a
    comment of ours."""
    kept, quote = [], None
    for line in lines:
        if quote is None:
            kept.append(line)
            opened = re.search(r'(\$*)("{3,})\s*$', line) or (re.search(r'@\$?"(?:[^"]|"")*$', line) and not line.rstrip().endswith('";'))
            if opened:
                quote = opened.group(2) if hasattr(opened, "group") and opened.re.pattern.startswith("(\\$*)") else '"'
        else:
            kept.append("")
            stripped = line.strip()
            if (quote != '"' and stripped.startswith(quote)) or (quote == '"' and re.search(r'(?<!")"(?!")', line)):
                quote = None
    return kept


def check_cs(lines):
    lines = code_only(lines)
    comment = lambda l: re.match(r"^\s*(//|/\*|\*)", l) is not None
    for first, count in runs(lines, lambda l: re.match(r"^\s*(//|/\*)", l) is not None, lambda l: "*/" in l or l.lstrip().startswith("//")):
        if re.match(r"^\s*#", lines[first]):
            continue
        after = subject(lines, first + count)
        doc = lines[first].lstrip().startswith("///")
        if not code_before(lines, first, comment) or re.match(r"^\s*(namespace|using)\b", after):
            yield first, "file", FILE_LIMIT, count
        elif TYPE.match(after):
            yield first, "type", TYPE_LIMIT, count
        elif doc or MEMBER.match(after) or after.lstrip().startswith("["):
            yield first, "member", MEMBER_LIMIT, count
        else:
            yield first, "body", BODY_LIMIT, count


def check_xml(lines):
    opened = lambda l: l.lstrip().startswith("<!--")
    closed = lambda l: "-->" in l
    seen_comment = False
    for first, count in runs(lines, opened, closed):
        if not seen_comment and not any(re.search(r"<[A-Za-z]", l) and not re.match(r"^\s*<(ResourceDictionary|Project|Styles|UserControl|Window|Application|\?xml)", l) for l in lines[:first]):
            yield first, "file", FILE_LIMIT, count
        else:
            yield first, "member", MEMBER_LIMIT, count
        seen_comment = True


def check_hash(lines, member_line, skip=r"^\s*(@.*)?$"):
    """Python, shell, the justfile, YAML: '#' runs (a shebang aside), a run before a definition (past `skip`'s lines) a
    member's."""
    comment = lambda l: re.match(r"^\s*#(?!!)", l) is not None
    for first, count in runs(lines, comment):
        if not code_before(lines, first, lambda l: comment(l) or l.startswith("#!")):
            yield first, "file", FILE_LIMIT, count
        elif member_line(subject(lines, first + count, skip)):
            yield first, "member", MEMBER_LIMIT, count
        else:
            yield first, "body", BODY_LIMIT, count


def check_python(lines):
    yield from check_hash(lines, lambda l: re.match(r"^(\s*(async\s+)?(def|class)\s|[A-Z_][A-Z0-9_]*\s*[:=])", l) is not None)
    # Docstrings: a module's, a class's or a function's, its triple quotes and the lines between.
    for at, line in enumerate(lines):
        stripped = line.strip()
        if not stripped.startswith(('"""', "'''")):
            continue
        quote = stripped[:3]
        before = next((l for l in reversed(lines[:at]) if l.strip() and not l.strip().startswith("#")), "")
        kind = "file" if not before or before.startswith("#!") else "type" if re.match(r"^\s*class\s", before) else \
            "member" if re.match(r"^\s*(async\s+)?def\s", before) else None
        if kind is None:
            continue
        end = at if stripped.count(quote) >= 2 and len(stripped) > 3 else next(
            (i for i in range(at + 1, len(lines)) if quote in lines[i]), at)
        limit = {"file": FILE_LIMIT, "type": TYPE_LIMIT, "member": MEMBER_LIMIT}[kind]
        yield at, kind + " docstring", limit, end - at + 1


def check_slash_script(lines):
    """JavaScript and CSS: '//' or '/* */' runs, a run before a function or rule a member's."""
    comment = lambda l: re.match(r"^\s*(//|/\*|\*)", l) is not None
    for first, count in runs(lines, lambda l: re.match(r"^\s*(//|/\*)", l) is not None, lambda l: "*/" in l or l.lstrip().startswith("//")):
        after = subject(lines, first + count, r"^\s*$")
        if not code_before(lines, first, comment):
            yield first, "file", FILE_LIMIT, count
        elif re.match(r"^\s*((async\s+)?function\b|(const|let)\s+\w+\s*=\s*(async\s*)?(\(|function)|[.#\w:\[\]*,\s>-]+\{\s*$|@)", after):
            yield first, "member", MEMBER_LIMIT, count
        else:
            yield first, "body", BODY_LIMIT, count


def checker(path):
    name = os.path.basename(path)
    extension = os.path.splitext(name)[1].lower()
    if extension == ".cs":
        return check_cs
    if extension in (".axaml", ".xaml", ".props", ".targets", ".csproj", ".html", ".xml") or name == "Directory.Packages.props":
        return check_xml
    if extension == ".py":
        return check_python
    if extension in (".sh",) or name == "justfile":
        # A recipe's attributes ([unix], [windows]) stand between it and its comment.
        return lambda lines: check_hash(lines, lambda l: re.match(r"^\s*([\w-]+\s*\(\)\s*\{|function\s|[\w-]+.*:\s*$|@?[\w-]+( [^=]*)?:( .*)?$)", l) is not None,
                                        r"^\s*(@.*|\[[^\]]*\])?$")
    if extension in (".yml", ".yaml"):
        return lambda lines: check_hash(lines, lambda l: re.match(r"^\s*(-\s+)?[\w-]+:", l) is not None)
    if extension in (".js", ".cjs", ".mjs", ".css"):
        return check_slash_script
    return None


def files(paths):
    for start in paths:
        if os.path.isfile(start):
            yield start
            continue
        for folder, folders, names in os.walk(start):
            folders[:] = [f for f in folders if not f.startswith(".") and f not in ("bin", "obj", "artifacts", "node_modules")]
            for name in names:
                yield os.path.join(folder, name)


def main():
    paths = [os.path.abspath(p) for p in sys.argv[1:]] or [ROOT]
    over = 0
    for path in sorted(files(paths)):
        check = checker(path)
        if check is None or not held(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as source:
            lines = source.read().split("\n")
        if written_by_tool(lines):
            continue
        for first, kind, limit, count in check(lines):
            if count > limit:
                over += 1
                print(f"{os.path.relpath(path, ROOT)}:{first + 1}: {kind} comment of {count} lines, at most {limit}")
    print(f"{over} comments over their limits", file=sys.stderr)
    return 1 if over else 0


if __name__ == "__main__":
    sys.exit(main())
